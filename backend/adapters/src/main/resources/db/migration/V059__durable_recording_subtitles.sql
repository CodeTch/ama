-- Technical work belongs to one actual recording, not one durable_task per chunk.
CREATE TABLE recording_subtitle_job (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 session_id CHAR(36) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NOT NULL,
 meeting_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 owner_id VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
 cancel_epoch BIGINT UNSIGNED NOT NULL,
 part_no INT UNSIGNED NOT NULL DEFAULT 1,
 processed_seq BIGINT UNSIGNED NOT NULL DEFAULT 0,
 processed_samples BIGINT UNSIGNED NOT NULL DEFAULT 0,
 part_offset_samples BIGINT UNSIGNED NOT NULL DEFAULT 0,
 window_start_seq BIGINT UNSIGNED NOT NULL DEFAULT 1,
 window_start_sample BIGINT UNSIGNED NOT NULL DEFAULT 0,
 window_revision INT UNSIGNED NOT NULL DEFAULT 0,
 event_counter BIGINT UNSIGNED NOT NULL DEFAULT 0,
 text_bytes BIGINT UNSIGNED NOT NULL DEFAULT 0,
 state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 attempt BIGINT UNSIGNED NOT NULL DEFAULT 0,
 lease_owner VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_expires_at DATETIME(6) NULL,
 next_run_at DATETIME(6) NOT NULL,
 error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 UNIQUE KEY subtitle_session(session_id),
 INDEX subtitle_due(state,next_run_at,id),
 CONSTRAINT fk_subtitle_job_session FOREIGN KEY(session_id) REFERENCES recording_session(session_id),
 CONSTRAINT fk_subtitle_job_meeting FOREIGN KEY(meeting_id) REFERENCES meeting(id),
 CONSTRAINT fk_subtitle_job_owner FOREIGN KEY(owner_id) REFERENCES enterprise_identity(enterprise_id),
 CONSTRAINT ck_subtitle_job_state CHECK(state IN ('IDLE','LEASED','DELAYED','DEFERRED','DONE','CANCELLED')),
 CONSTRAINT ck_subtitle_job_lease CHECK((state='LEASED' AND lease_owner IS NOT NULL AND lease_expires_at IS NOT NULL) OR (state<>'LEASED' AND lease_owner IS NULL AND lease_expires_at IS NULL)),
 CONSTRAINT ck_subtitle_job_bounds CHECK(part_no BETWEEN 1 AND 16 AND processed_seq<=4608 AND window_start_seq<=4609 AND processed_samples<=115200000 AND part_offset_samples<=115200000 AND window_start_sample<=processed_samples AND window_revision<=2 AND event_counter<=9232 AND text_bytes<=33554432)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;

CREATE TABLE recording_subtitle_event (
 session_id CHAR(36) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NOT NULL,
 event_no BIGINT UNSIGNED NOT NULL,
 job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 meeting_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 part_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 segment_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 revision INT UNSIGNED NOT NULL,
 status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 body LONGTEXT NOT NULL,
 text_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source_fingerprint_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 engine_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 execution_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source_final_seq BIGINT UNSIGNED NOT NULL,
 start_ms BIGINT UNSIGNED NOT NULL,
 end_ms BIGINT UNSIGNED NOT NULL,
 created_at DATETIME(6) NOT NULL,
 PRIMARY KEY(session_id,event_no),
 UNIQUE KEY subtitle_revision(session_id,segment_id,revision),
 CONSTRAINT fk_subtitle_event_job FOREIGN KEY(job_id) REFERENCES recording_subtitle_job(id),
 CONSTRAINT fk_subtitle_event_session FOREIGN KEY(session_id) REFERENCES recording_session(session_id),
 CONSTRAINT fk_subtitle_event_meeting FOREIGN KEY(meeting_id) REFERENCES meeting(id),
 CONSTRAINT fk_subtitle_event_execution FOREIGN KEY(execution_id) REFERENCES speech_execution(id),
 CONSTRAINT ck_subtitle_event_status CHECK(status IN ('temporary','stable')),
 CONSTRAINT ck_subtitle_event_bounds CHECK(event_no BETWEEN 1 AND 9232 AND revision BETWEEN 1 AND 3 AND source_final_seq BETWEEN 1 AND 4608 AND end_ms>start_ms AND end_ms<=7200000 AND OCTET_LENGTH(body)<=65536)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
