-- Explicit, recoverable copies of genuine completed recording archives.
CREATE TABLE recording_transcript_source (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 session_id CHAR(36) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NOT NULL,
 archive_id CHAR(36) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NOT NULL,
 meeting_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 owner_id VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
 cancel_epoch BIGINT UNSIGNED NOT NULL,
 original_file_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source_bytes BIGINT UNSIGNED NOT NULL,
 source_samples BIGINT UNSIGNED NOT NULL,
 upload_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 copy_file_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 attempt BIGINT UNSIGNED NOT NULL DEFAULT 0,
 lease_owner VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_expires_at DATETIME(6) NULL,
 next_run_at DATETIME(6) NOT NULL,
 error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 UNIQUE KEY recording_transcript_session(session_id),
 UNIQUE KEY recording_transcript_archive(archive_id),
 UNIQUE KEY recording_transcript_upload(upload_id),
 UNIQUE KEY recording_transcript_file(copy_file_id),
 INDEX recording_transcript_due(state,next_run_at,id),
 CONSTRAINT fk_recording_transcript_session FOREIGN KEY(session_id) REFERENCES recording_session(session_id),
 CONSTRAINT fk_recording_transcript_archive FOREIGN KEY(archive_id) REFERENCES recording_archive(id),
 CONSTRAINT fk_recording_transcript_meeting FOREIGN KEY(meeting_id) REFERENCES meeting(id),
 CONSTRAINT fk_recording_transcript_owner FOREIGN KEY(owner_id) REFERENCES enterprise_identity(enterprise_id),
 CONSTRAINT fk_recording_transcript_original FOREIGN KEY(original_file_id) REFERENCES file_object(id),
 CONSTRAINT fk_recording_transcript_upload FOREIGN KEY(upload_id) REFERENCES upload_session(id),
 CONSTRAINT fk_recording_transcript_copy FOREIGN KEY(copy_file_id) REFERENCES file_object(id),
 CONSTRAINT ck_recording_transcript_state CHECK(state IN ('PENDING','LEASED','DELAYED','READY','CANCELLED')),
 CONSTRAINT ck_recording_transcript_lease CHECK((state='LEASED' AND lease_owner IS NOT NULL AND lease_expires_at IS NOT NULL) OR (state<>'LEASED' AND lease_owner IS NULL AND lease_expires_at IS NULL)),
 CONSTRAINT ck_recording_transcript_ready CHECK((state='READY' AND upload_id IS NOT NULL AND copy_file_id IS NOT NULL) OR (state<>'READY' AND copy_file_id IS NULL)),
 CONSTRAINT ck_recording_transcript_size CHECK(source_samples BETWEEN 1 AND 115200000 AND source_bytes=44+source_samples*2 AND source_bytes<=230400044)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
