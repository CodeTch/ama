"""Pure render/preservation audit. Never calls schema verify/container/runtime code."""
import copy
import hashlib
import json
from pathlib import Path
import runpy
import subprocess

BASE = "214a63d978e4c04c0b3aec1c99d8d0ce3c093d9d"
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OVERRIDES = {".gitattributes", "docs/acceptance/b/material-provenance-design-prerequisite.md",
             "docs/database/ama-data-dictionary.md", "docs/superpowers/specs/2026-10-21-ama-database-design.md",
             "docs/superpowers/specs/2026-10-22-ama-material-provenance-addendum.md", "tools/checks/database_design.py"}
CHECKS = []


def check(label, condition):
    assert condition, label
    CHECKS.append(label)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT)


def original(path):
    return git("show", BASE + ":" + path)


def main():
    check("same original author branch", git("branch", "--show-current").decode().strip() == "codex/phase-b-provenance-design")
    check("exact original base is ancestor", subprocess.run(["git", "merge-base", "--is-ancestor", BASE, "HEAD"], cwd=ROOT).returncode == 0)
    # Both modules are loaded without __main__; no subprocess/container verifier is invoked.
    source = ROOT / "tools/checks/database_design.py"
    current = runpy.run_path(str(source), run_name="pure_current_schema")
    baseline = {"__file__": str(source), "__name__": "pure_original_schema"}
    exec(compile(original("tools/checks/database_design.py"), str(source), "exec"), baseline)
    check("version remains proposed/unallocated", current["VERSION"] == baseline["VERSION"] == "B00-1.4-proposed")
    old_tables, new_tables = copy.deepcopy(baseline["TABLES"]), copy.deepcopy(current["TABLES"])
    for rows in (old_tables, new_tables):
        for row in rows:
            row.pop("policy")
    check("all 96 relation/column/index/FK/CHECK declarations unchanged", old_tables == new_tables and len(new_tables) == 96)
    policy_changes = [a["name"] for a, b in zip(current["TABLES"], baseline["TABLES"]) if a["policy"] != b["policy"]]
    check("only element explanatory policy changed", policy_changes == ["minutes_element"])
    for path, rendered in current["generated"]().items():
        check("generated bytes: " + path, (ROOT / path).read_bytes() == rendered.encode())
    check("review DDL remains original bytes", (ROOT / "docs/database/ama-schema-draft.sql").read_bytes() == original("docs/database/ama-schema-draft.sql"))
    spec = (ROOT / "docs/superpowers/specs/2026-10-21-ama-database-design.md").read_text()
    check("generated complete ER has no drift", "## 附录：完整 ER" + spec.split("## 附录：完整 ER", 1)[1] == current["er"]())
    check("complete ER entities and relationships unchanged", current["er"]().split("```mermaid", 1)[1] == baseline["er"]().split("```mermaid", 1)[1])
    for text in (spec, (ROOT / "docs/database/ama-data-dictionary.md").read_text()):
        check("single shared rendered root-rule paragraph", text.count(current["PROVENANCE_ROOT_RULE"]) == 1)
    addendum = (ROOT / "docs/superpowers/specs/2026-10-22-ama-material-provenance-addendum.md").read_text()
    check("old normative zero-evidence-only recipe removed", "Zero-evidence element source_context_id values are explicit context roots" not in addendum and "A zero-evidence element is an explicit context root" not in addendum)
    check("single exact per-domain recipe specified", "**B(D) ∪ U(D)**" in addendum and "regardless of evidence count" in addendum)
    inventory_path = HERE / "original-review/task-D-01-provenance-design-delivery-paths.json"
    check("original delivery inventory SHA", digest(inventory_path.read_bytes()) == "5fd3020b7e2866e9aa56f0c1c77ebcb1a83be06e6cba3bdb5bc8e41a7d42df70")
    inventory = json.loads(inventory_path.read_text())
    check("original65 path count", len(inventory) == 65)
    records, preserved = [], 0
    for item in inventory:
        path = item["path"]
        before, now = original(path), (ROOT / path).read_bytes()
        check("BASE inventory bytes: " + path, len(before) == item["size"] and digest(before) == item["sha256"])
        if path not in OVERRIDES:
            check("original bytes preserved: " + path, before == now)
            preserved += 1
        records.append(dict(path=path, disposition="current normative override" if path in OVERRIDES else "original bytes preserved",
                            baseBytes=len(before), baseSha256=digest(before), currentBytes=len(now), currentSha256=digest(now)))
    immutable = json.loads((ROOT / "artifacts/phase-b/b00-provenance-design/baseline-immutable-files.json").read_text())
    for path, info in immutable.items():
        raw = (ROOT / path).read_bytes()
        check("original35 immutable bytes: " + path, len(raw) == info["bytes"] and digest(raw) == info["sha256"])
    historical = ROOT / "artifacts/phase-b/b00-provenance-design/historical-projection-vectors.json"
    check("original93 whitelist vectors not regenerated", len(json.loads(historical.read_text())) == 93 and historical.read_bytes() == original(str(historical.relative_to(ROOT))))
    raw = bytes.fromhex((ROOT / "artifacts/phase-b/b00-provenance-design/task-D-01-provenance-draft-exclusion-vector.hex").read_text())
    check("original6871byte vector preserved", len(raw) == 6871 and digest(raw) == "015a3a30f9970d41ef3ac45209794c7a4367e494b53a4f314f6cd0f0d3728112")
    review_hashes = {"task-D-01-provenance-design-review.md": "0803c06ab1ca427e9d8b2d2007704c07cf85cf30d959da3649374cc1574b74b0",
                     "task-D-01-provenance-design-review-context-roots.json": "6644ddf1cd0e70d334cc8d35511b309a9b4919ab1fbfe62889656c6d95dfc3c2",
                     "task-D-01-provenance-design-review-offline.py": "ddfa0be3007c78b795b61455c3d48d7cfdd3a4224b70eb0ce0f02c8b41782956",
                     "task-D-01-provenance-design-review-offline.json": "67a33ac618c8a753ac2b82b5408df63f816788538dee6955e0317e468fe95fef",
                     "task-D-01-provenance-design-fix1-brief.md": "b729049728ec174e312b8d712f4f9d5235ca813e3e14d41be9d918dbb87b6b90"}
    for path, sha in review_hashes.items():
        check("copied independent original SHA: " + path, digest((HERE / "original-review" / path).read_bytes()) == sha)
    changed = set(git("diff", "--name-only", BASE).decode().splitlines())
    # A new tracked consumer record is allowed; all prior tracked bytes outside the six are fixed.
    check("no old tracked path changed outside exact override allowlist", changed <= OVERRIDES | {"docs/acceptance/b/material-provenance-design-fix1-report.md"} | set(git("ls-files", "--others", "--ignored", "--exclude-standard", "artifacts/phase-b/b00-provenance-design-fix1").decode().splitlines()) | {str(p.relative_to(ROOT)) for p in HERE.rglob("*") if p.is_file()})
    attrs = git("check-attr", "text", "--", *[str(p.relative_to(ROOT)) for p in HERE.rglob("*") if p.is_file()]).decode().splitlines()
    check("all new archive paths use -text", all(line.endswith(": text: unset") for line in attrs))
    result = dict(scope=__doc__, base=BASE, assertions=len(CHECKS), checks=CHECKS, original65=records,
                  preservedOriginalPaths=preserved, currentNormativeOverrides=sorted(OVERRIDES), originalImmutablePaths=len(immutable),
                  qualification="Pure render/set-profile preservation; no DB, Docker, network, original cohort, runtime or adoption checks.")
    (HERE / "render-preservation-verification.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({k: result[k] for k in ("base", "assertions", "preservedOriginalPaths", "originalImmutablePaths", "qualification")}))


if __name__ == "__main__":
    main()
