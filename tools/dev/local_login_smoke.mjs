import assert from 'node:assert/strict';

const base=process.env.AMA_LOCAL_URL??'http://127.0.0.1:5173';
const casOrigin=process.env.AMA_CAS_ORIGIN??'http://127.0.0.1:8787';
const service=`${base}/auth/cas/callback`;
const login=await fetch(`${casOrigin}/cas/login`,{method:'POST',headers:{'content-type':'application/x-www-form-urlencoded'},body:new URLSearchParams({service,username:'dev-owner',password:'dev-password'}),redirect:'manual'});
assert.equal(login.status,303,'CAS provider must issue a browser service ticket');
const location=login.headers.get('location')??'';
const ticket=new URL(location).searchParams.get('ticket');
assert.match(ticket??'',/^ST-[A-Za-z0-9_-]{8,512}$/);
const validated=await fetch(`${casOrigin}/cas/p3/serviceValidate?service=${encodeURIComponent(service)}&ticket=${encodeURIComponent(ticket)}`);
const xml=await validated.text();
assert.equal(validated.status,200);
assert.match(xml,/<cas:authenticationSuccess>/);
assert.match(xml,/<cas:user>dev-owner<\/cas:user>/);
const reused=await fetch(`${casOrigin}/cas/p3/serviceValidate?service=${encodeURIComponent(service)}&ticket=${encodeURIComponent(ticket)}`);
assert.equal(reused.status,200);
assert.match(await reused.text(),/INVALID_TICKET/);
const rejected=await fetch(`${casOrigin}/cas/login`,{method:'POST',headers:{'content-type':'application/x-www-form-urlencoded'},body:new URLSearchParams({service:'http://attacker.invalid/callback',username:'dev-owner',password:'dev-password'})});
assert.equal(rejected.status,400,'CAS service registration must reject unregistered callbacks');
console.log(JSON.stringify({pass:true,checks:['cas-login-redirect','cas-xml-validation','cas-single-use-ticket','cas-service-allowlist']}));
